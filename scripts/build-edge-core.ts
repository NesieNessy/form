/**
 * Bundles lib/ai/edgeCore.ts into one plain-JavaScript module the Deno edge
 * function can import. Run with `npm run build:edge-core` after changing
 * anything under lib/ that the assistant uses; a test fails if the committed
 * bundle is out of date.
 */
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '..');
export const BUNDLE_PATH = join(ROOT, 'supabase', 'functions', '_shared', 'core.js');

const BANNER = '// GENERATED by `npm run build:edge-core` from lib/ai/edgeCore.ts. Do not edit.\n';

export function buildEdgeCore(): string {
  const result = buildSync({
    entryPoints: [join(ROOT, 'lib', 'ai', 'edgeCore.ts')],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    platform: 'neutral',
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  // Line endings are normalized so the up-to-date check gives the same answer on every OS.
  return (BANNER + result.outputFiles[0].text).replace(/\r\n/g, '\n');
}

export function readCommittedBundle(): string {
  return readFileSync(BUNDLE_PATH, 'utf8').replace(/\r\n/g, '\n');
}

if (require.main === module) {
  writeFileSync(BUNDLE_PATH, buildEdgeCore());
  console.log(`Wrote ${BUNDLE_PATH}`);
}
